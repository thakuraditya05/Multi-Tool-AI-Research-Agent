# backend.py


import os
import sqlite3
import requests
from dotenv import load_dotenv

from langgraph.graph import StateGraph, START, END
from typing import TypedDict, Annotated
from langchain_core.messages import BaseMessage, HumanMessage
from langgraph.checkpoint.sqlite import SqliteSaver
from langgraph.graph.message import add_messages
from langgraph.prebuilt import ToolNode, tools_condition
from langchain_core.tools import tool

# -------------------
# New Imports Added
# -------------------
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_community.tools.tavily_search import TavilySearchResults
from langchain_experimental.tools import PythonREPLTool

load_dotenv()

# -------------------
# 1. LLM
# -------------------
llm = ChatGoogleGenerativeAI(
    model="gemini-3.5-flash-lite",
    temperature=0,
    google_api_key=os.environ.get("GEMINI_API_KEY_TOOL")
)

# -------------------
# 2. Tools
# -------------------

# Tool 1: Tavily Search (Better than DuckDuckGo for Agents)
# Requires TAVILY_API_KEY in .env
search_tool = TavilySearchResults(max_results=3, search_depth="advanced")

# Tool 2: Code Interpreter
# Allows the LLM to write and run Python code for data analysis or math
python_repl_tool = PythonREPLTool()

@tool
def calculator(first_num: float, second_num: float, operation: str) -> dict:
    """
    Perform a basic arithmetic operation on two numbers.
    Supported operations: add, sub, mul, div
    """
    try:
        if operation == "add": result = first_num + second_num
        elif operation == "sub": result = first_num - second_num
        elif operation == "mul": result = first_num * second_num
        elif operation == "div":
            if second_num == 0: return {"error": "Division by zero is not allowed"}
            result = first_num / second_num
        else:
            return {"error": f"Unsupported operation '{operation}'"}
        return {"first_num": first_num, "second_num": second_num, "operation": operation, "result": result}
    except Exception as e:
        return {"error": str(e)}

@tool
def get_stock_price(symbol: str) -> dict:
    """
    Fetch latest stock price for a given symbol (e.g. 'AAPL', 'TSLA') 
    using Alpha Vantage.
    """
    url = f"https://www.alphavantage.co/query?function=GLOBAL_QUOTE&symbol={symbol}&apikey=C9PE94QUEW9VWGFM"
    r = requests.get(url)
    return r.json()

@tool
def analyze_transaction_anomaly(amount: float, location: str, account_age_days: int) -> dict:
    """
    Analyzes a banking transaction to detect potential money laundering or anomalies.
    Returns a risk score and fraud flag.
    """
    risk_score = 0
    # Rule-based logic (can be replaced with a real ML model later)
    if amount > 10000: risk_score += 40
    if location not in ["US", "IN"]: risk_score += 30
    if account_age_days < 30: risk_score += 30

    is_anomaly = risk_score >= 70
    status = "High-Risk: Potential Money Laundering Flagged" if is_anomaly else "Normal Transaction"
    
    return {
        "analyzed_amount": amount,
        "risk_score": risk_score,
        "is_anomaly": is_anomaly,
        "status": status
    }

# Combine all tools
tools = [search_tool, get_stock_price, calculator, python_repl_tool, analyze_transaction_anomaly]
llm_with_tools = llm.bind_tools(tools)

# -------------------
# 3. State
# -------------------
class ChatState(TypedDict):
    messages: Annotated[list[BaseMessage], add_messages]

# -------------------
# 4. Nodes
# -------------------
def chat_node(state: ChatState):
    """LLM node that may answer or request a tool call."""
    messages = state["messages"]
    response = llm_with_tools.invoke(messages)
    return {"messages": [response]}

tool_node = ToolNode(tools)

# -------------------
# 5. Checkpointer
# -------------------
conn = sqlite3.connect(database="chatbot.db", check_same_thread=False)
checkpointer = SqliteSaver(conn=conn)

# -------------------
# 6. Graph
# -------------------
graph = StateGraph(ChatState)
graph.add_node("chat_node", chat_node)
graph.add_node("tools", tool_node)

graph.add_edge(START, "chat_node")
graph.add_conditional_edges("chat_node", tools_condition)
graph.add_edge('tools', 'chat_node')

chatbot = graph.compile(checkpointer=checkpointer)

# -------------------
# 7. Helper
# -------------------
def retrieve_all_threads():
    all_threads = set()
    for checkpoint in checkpointer.list(None):
        all_threads.add(checkpoint.config["configurable"]["thread_id"])
    return list(all_threads)
































